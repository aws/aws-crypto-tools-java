#!/usr/bin/env python3
"""Extract the fixed RSA and ECDH test values from the Dafny-based MPL's tests into JSON.

Usage: scripts/extract-asymmetric-vectors.py <mpl-checkout-or-archive> <output-dir>
Reads AwsCryptographyPrimitives/test/TestRSA.dfy and TestECDH.dfy; writes asymmetric.json.
TestSignature.dfy has no fixed values.
"""
import json
import re
import sys

LITERAL = re.compile(r'"((?:[^"\\]|\\.)*)"')


def concatenation(body):
    """The value of a Dafny expression made of string literals joined by +."""
    return ''.join(json.loads('"' + part + '"') for part in LITERAL.findall(body))


def constants(text):
    """Every `const NAME := "..." + ...` whose value is only string literals."""
    out = {}
    for name, body in re.findall(r'const (\w+)\s*:=\s*((?:\s*\+?\s*"(?:[^"\\]|\\.)*")+)', text):
        out[name] = concatenation(body)
    return out


def functions(text):
    """Every `opaque function NAME(): string { "..." + ... }`."""
    out = {}
    for name, body in re.findall(r'function (\w+)\(\)\s*:\s*string\s*\{(.*?)\}', text, re.S):
        out[name] = concatenation(body)
    return out


def hex_bytes(loose):
    """HexStrings.FromHexString: an odd-length string's first digit is a byte of its own."""
    if len(loose) % 2 == 1:
        loose = '0' + loose
    return bytes.fromhex(loose).hex()


root, out_dir = sys.argv[1], sys.argv[2]
test = root + '/AwsCryptographyPrimitives/test/'

rsa = open(test + 'TestRSA.dfy').read()
rsa_consts, rsa_functions = constants(rsa), functions(rsa)

ecdh = open(test + 'TestECDH.dfy').read()
c = constants(ecdh)
curves = ['ECC_NIST_P256', 'ECC_NIST_P384', 'ECC_NIST_P521']

vectors = {
    'rsaPublicKeys': [
        {'lengthBits': bits, 'pem': rsa_consts['RSA_PUBLIC_%d' % bits]} for bits in (2048, 3072, 4096)
    ],
    'rsaKeyPairs': [
        {
            'name': 'generated by GenerateRSAKeyPair',
            'lengthBits': 2048,
            'publicPem': rsa_functions['StaticPublicKeyFromGenerateRSAKeyPair'],
            'privatePem': rsa_functions['StaticPrivateKeyFromGenerateRSAKeyPair'],
        },
        {
            'name': 'public test vectors, private PEM without the public key',
            'lengthBits': 4096,
            'publicPem': rsa_functions['StaticPublicKeyFromTestVectors'],
            'privatePem': rsa_functions['StaticPrivateKeyFromTestVectors'],
        },
    ],
    'ecdhKeys': [
        {'curve': curve, 'privatePem': c[private], 'publicDer': hex_bytes(c[public]), 'compressed': hex_bytes(c[compressed])}
        for curve, private, public, compressed in zip(
            curves,
            ['ECC_P256_PRIVATE', 'ECC_P384_PRIVATE', 'ECC_P521_PRIVATE'],
            ['ECC_P256_PUBLIC', 'ECC_384_PUBLIC', 'ECC_P521_PUBLIC'],
            ['ECC_P256_PUBLIC_COMPRESSED', 'ECC_384_PUBLIC_COMPRESSED', 'ECC_P521_PUBLIC_COMPRESSED'],
        )
    ],
    'ecdhInvalidPublicKeys': [
        {'curve': curve, 'name': name, 'der': hex_bytes(c[name]), 'javaMessage': message}
        for names, message in [
            (['ECC_256_PUBLIC_INF_FAIL_ON_LOAD', 'ECC_384_PUBLIC_INF_FAIL_ON_LOAD', 'ECC_521_PUBLIC_INF_FAIL_ON_LOAD'],
             c['INFINITY_POINT_ERR_MSG_JAVA']),
            (['ECC_P256_PUBLIC_GP_FAIL_ON_LOAD', 'ECC_P384_PUBLIC_GP_FAIL_ON_LOAD', 'ECC_P521_PUBLIC_GP_FAIL_ON_LOAD'],
             c['OUT_OF_BOUNDS_ERR_MSG_JAVA']),
            (['ECC_256_PUBLIC_INF', 'ECC_384_PUBLIC_INF', 'ECC_521_PUBLIC_INF'], None),
            (['ECC_P256_PUBLIC_GP', 'ECC_P384_PUBLIC_GP', 'ECC_P521_PUBLIC_GP'], None),
        ]
        for curve, name in zip(curves, names)
    ],
}
json.dump(vectors, open(out_dir + '/asymmetric.json', 'w'), indent=2)
